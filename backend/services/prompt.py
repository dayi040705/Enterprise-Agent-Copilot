# 3. LLM Judge — Faithfulness (答案忠实度)
# ============================================================

FAITHFULNESS_JUDGE_PROMPT = """你是一个严格的 RAG 评测裁判。请按以下步骤打分:

## 检索到的上下文 (只能以此为判断依据):
{context_text}

## 模型生成的答案:
{answer}

## 评分步骤:
1. 把答案拆成独立的"事实断言"(claims)
2. 逐条判断每个 claim 是否能在上下文中找到依据
3. 打分: 有依据的 claims / 总 claims

## 输出格式 (严格JSON):
{{"claims": ["claim1", "claim2", ...], "verdicts": ["有依据"/"无依据", ...], "score": 0.0~1.0, "explanation": "一句话说明扣分原因"}}"""


# ============================================================
# 4. LLM Judge — Answer Relevancy (答案相关性)
# ============================================================

RELEVANCY_JUDGE_PROMPT = """你是一个严格的 RAG 评测裁判。请判断答案是否回答了问题。

## 用户问题:
{question}

## 模型回答:
{answer}

## 评分标准:
- 1.0: 答案完全针对问题, 直接给出结果
- 0.7-0.9: 基本回答, 部分内容略偏
- 0.4-0.6: 部分相关, 但有不少无关信息
- 0.1-0.3: 基本不相关, 答非所问
- 0.0: 完全跑题

## 输出格式 (严格JSON):
{{"score": 0.0~1.0, "is_relevant": true/false, "explanation": "一句话说明"}}"""
